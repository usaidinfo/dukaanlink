export function isKiranaStarterShop(category) {
  const value = String(category || "").toLowerCase();
  if (value.includes("boutique") || value.includes("gift")) return false;
  return value.includes("kirana") || value.includes("retail");
}

export function kiranaItemLabel(item, locale) {
  if (locale === "hi") return item.name_hi || item.name;
  return item.name;
}

export function remainingKiranaStarter(existingItems = [], usedIds = []) {
  const used = new Set(usedIds || []);
  const taken = new Set(
    (existingItems || []).flatMap((row) => {
      const name = String(row?.name || "").trim().toLowerCase();
      return name ? [name] : [];
    })
  );
  return KIRANA_STARTER_ITEMS.filter((item) => {
    if (used.has(item.id)) return false;
    const en = String(item.name || "").trim().toLowerCase();
    const hi = String(item.name_hi || "").trim().toLowerCase();
    return !taken.has(en) && !(hi && taken.has(hi));
  });
}

const usedStarterKey = (businessId) => `dukaanlink-starter-used-${businessId}`;

export function getUsedStarterIds(businessId) {
  if (!businessId || typeof window === "undefined") return [];
  try {
    const raw = window.localStorage.getItem(usedStarterKey(businessId));
    const list = JSON.parse(raw || "[]");
    return Array.isArray(list) ? list.filter(Boolean) : [];
  } catch {
    return [];
  }
}

export function rememberUsedStarterIds(businessId, ids) {
  if (!businessId || typeof window === "undefined") return getUsedStarterIds(businessId);
  const next = new Set(getUsedStarterIds(businessId));
  (ids || []).forEach((id) => {
    if (id) next.add(id);
  });
  const list = [...next];
  try {
    window.localStorage.setItem(usedStarterKey(businessId), JSON.stringify(list));
  } catch {
    /* ignore quota */
  }
  return list;
}

export function groupKiranaStarter(items, query = "") {
  const q = String(query || "").trim().toLowerCase();
  const filtered = !q
    ? items
    : items.filter((item) => {
        const hay = `${item.name} ${item.name_hi} ${item.category}`.toLowerCase();
        return hay.includes(q);
      });
  const map = new Map();
  for (const item of filtered) {
    if (!map.has(item.category)) map.set(item.category, []);
    map.get(item.category).push(item);
  }
  return KIRANA_STARTER_CATEGORIES
    .map((category) => ({ category, items: map.get(category) || [] }))
    .filter((group) => group.items.length);
}

